#include<bits/stdc++.h>
using namespace std;

int main(){
	int a = 5;

	cout << a << endl;			//5
	cout << a++ << endl;		//5
	cout << a << endl;			//6
	cout << ++a << endl;		//7
	cout << a << endl;			//7
	cout << a-- << endl;		//7
	cout << a << endl;			//6
	cout << --a << endl;		//5
	cout << a << endl;			//5


	while(a--){
		cout << "bangladesh" << endl;
	}
}